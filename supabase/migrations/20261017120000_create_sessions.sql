-- Server-side sessions created by the sign-in flow (specs/sign-in.md)
create table public.sessions (
  id text primary key,                          -- nanoid generated by the API
  account_id text not null references public.accounts (id) on delete cascade,
  token_hash text not null unique,              -- SHA-256 of the session token, never the token itself
  created_at timestamptz not null default now(),
  expires_at timestamptz not null               -- created_at + 7 days, set by the API
);

create index sessions_account_id_idx on public.sessions (account_id);

-- No policies: only the server (service role) can read or write sessions.
alter table public.sessions enable row level security;
