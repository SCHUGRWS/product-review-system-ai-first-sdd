-- Product reviews posted by signed-in users (specs/feedback.md)
create table public.feedbacks (
  id text primary key,                          -- nanoid generated by the API
  account_id text not null
    references public.accounts (id) on delete cascade, -- author, taken from the session
  product_name text not null
    check (char_length(product_name) between 2 and 120),
  rating smallint not null check (rating between 1 and 5),
  comment text not null
    check (char_length(comment) between 10 and 2000),
  created_at timestamptz not null default now()
);

-- "My feedback, newest first" (feedback.listMine, RecentFeedback)
create index feedbacks_account_created_idx
  on public.feedbacks (account_id, created_at desc);

-- No policies: only the server (service role) can read or write feedbacks.
alter table public.feedbacks enable row level security;
