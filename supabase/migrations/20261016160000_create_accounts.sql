-- Accounts created through the sign-up flow (specs/sign-up.md)
create table public.accounts (
  id text primary key,                          -- nanoid generated by the API
  first_name text not null,
  last_name text not null,
  email text not null unique,                   -- normalized (trimmed, lowercased) by the API
  password text not null,                       -- bcrypt hash, never the plain password
  salt text not null,                           -- bcrypt salt (also embedded in the hash)
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- No policies: only the server (service role) can read or write accounts.
alter table public.accounts enable row level security;
