// Step 3: turn the JSON files in this folder into the idempotent data migration
// supabase/migrations/20261018210000_demo_data.sql. Deterministic: the same JSON
// always gives the same SQL. Optional summaries.json adds cached AI summaries.
// Usage: node scripts/demo-data/build-migration.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const DIR = new URL(".", import.meta.url).pathname;
const OUT = new URL(
  "../../supabase/migrations/20261018210000_demo_data.sql",
  import.meta.url,
).pathname;
const read = (f) => JSON.parse(readFileSync(DIR + f, "utf8"));

const products = read("products.json");
const accounts = read("accounts.json");
const existing = read("existing-demo.json");
const feedbacks = [...existing.feedbacks, ...read("feedbacks.json")];
const summaries = existsSync(`${DIR}summaries.json`)
  ? read("summaries.json")
  : [];

// Only synthetic accounts may ever be exported
const SYNTHETIC = /^(demo|demo-[a-z]+|[a-z]+\.[a-z]+\.\d+)@example\.com$/;
for (const a of accounts)
  if (!SYNTHETIC.test(a.email))
    throw new Error(`refusing non-synthetic account ${a.email}`);
const accountIds = new Set(accounts.map((a) => a.id));
for (const f of feedbacks)
  if (!accountIds.has(f.account_id))
    throw new Error(`feedback ${f.id} has a non-demo author`);

const lit = (v) =>
  v === null || v === undefined
    ? "null"
    : typeof v === "number" || typeof v === "boolean"
      ? String(v)
      : typeof v === "object"
        ? `'${JSON.stringify(v).replaceAll("'", "''")}'::jsonb`
        : `'${String(v).replaceAll("'", "''")}'`;
const byId = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);

function insert(_table, cols, rows, tail, chunk = 500) {
  const out = [];
  for (let i = 0; i < rows.length; i += chunk) {
    const values = rows
      .slice(i, i + chunk)
      .map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`)
      .join(",\n");
    out.push(tail(cols.join(", "), values));
  }
  return out.join("\n\n");
}

const P = [
  "id",
  "asin",
  "title",
  "url",
  "image_url",
  "price_cents",
  "list_price_cents",
  "discount_percent",
  "currency",
  "rating",
  "review_count",
  "category_slug",
  "category_name",
  "first_seen_at",
  "last_seen_at",
];
const A = [
  "id",
  "first_name",
  "last_name",
  "email",
  "password",
  "salt",
  "active",
  "created_at",
];
const F = [
  "id",
  "account_id",
  "product_id",
  "product_name",
  "rating",
  "comment",
  "created_at",
];
const S = [
  "product_id",
  "locale",
  "summary",
  "review_count",
  "model",
  "generated_at",
];

const sql = `-- Demo data (specs/demo-data.md). GENERATED by scripts/demo-data/build-migration.mjs
-- from the JSON files next to it; do not edit by hand.
-- Idempotent: every insert skips rows that already exist, so it is safe on a
-- database that has real data. Only synthetic @example.com accounts are included;
-- demo@example.com / demo-review-2026 is the public demo login, every other demo
-- account has a random, discarded password.
-- Counts: ${products.length} products, ${accounts.length} accounts, ${feedbacks.length} feedbacks, ${summaries.length} summaries.

-- Products (ids kept so feedback references stay valid)
${insert("public.products", P, [...products].sort(byId), (c, v) => `insert into public.products (${c}) values\n${v}\non conflict do nothing;`)}

-- Synthetic accounts
${insert("public.accounts", A, [...accounts].sort(byId), (c, v) => `insert into public.accounts (${c}) values\n${v}\non conflict do nothing;`)}

-- Feedback. Joined to accounts/products so a row whose author or product was
-- skipped above (an existing email or asin with another id) is skipped too.
${insert(
  "public.feedbacks",
  F,
  [...feedbacks].sort(byId),
  (c, v) => `insert into public.feedbacks (${c})
select v.id, v.account_id, v.product_id, v.product_name, v.rating::smallint, v.comment, v.created_at::timestamptz
from (values\n${v}\n) as v (${c})
join public.accounts a on a.id = v.account_id
join public.products p on p.id = v.product_id
on conflict do nothing;`,
)}

-- Cached AI summaries (from scripts/demo-data/summaries.json, filled in wave 2)
${
  summaries.length === 0
    ? "-- none yet"
    : insert(
        "public.product_feedback_summaries",
        S,
        [...summaries].sort((a, b) =>
          (a.product_id + a.locale).localeCompare(b.product_id + b.locale),
        ),
        (c, v) => `insert into public.product_feedback_summaries (${c})
select v.product_id, v.locale, v.summary, v.review_count::integer, v.model, v.generated_at::timestamptz
from (values\n${v}\n) as v (${c})
join public.products p on p.id = v.product_id
on conflict do nothing;`,
      )
}
`;
writeFileSync(OUT, sql);
console.log({
  out: OUT,
  bytes: sql.length,
  products: products.length,
  accounts: accounts.length,
  feedbacks: feedbacks.length,
  summaries: summaries.length,
});
